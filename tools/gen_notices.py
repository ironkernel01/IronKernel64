# gen_notices.py -- writes docs/THIRD_PARTY_NOTICES.md: for every entry of tools/third_party.json its source
#   line and the licence files installed under third_party/<name>/ (verbatim), then the licence texts kept in
#   docs/licenses/ for items that are not installed there (lwIP from the Vitis install, Digilent MIT files),
#   the X11 notice of open-roms/pngprepare.c, and the repository's own LICENSE. Identical texts are printed
#   once and referred to afterwards.
# Usage: python -I tools/gen_notices.py      (run from the repository root; needs the installed third_party/)
# Revision: 11-10-2026
import hashlib
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
LICENSE_FILES = {
    "libsmb2": ["LICENCE-LGPL-2.1.txt", "COPYING"],
    "open-roms": ["LICENSE", "COPYING", "COPYING.LESSER"],
    "resid": ["COPYING", "AUTHORS"],
    "dormann": ["license.txt"],
    "redip-sid": ["LICENSE"],
}
EXTRAS = [
    ("lwIP 2.2.0 (Vitis install, ThirdParty/sw_services/lwip220_v1_4)", "BSD-3-Clause", "docs/licenses/lwip-2.2.0-COPYING.txt"),
    ("Digilent master XDC (github.com/Digilent/digilent-xdc)", "MIT", "docs/licenses/digilent-xdc-LICENSE.txt"),
    ("Digilent board files (github.com/Digilent/vivado-boards)", "MIT", "docs/licenses/digilent-vivado-boards-LICENSE.txt"),
]
seen = {}


def text_block(rel, out):
    path = os.path.join(ROOT, rel)
    if not os.path.isfile(path):
        out.append("*File not found: `%s` (run `python -I tools/setup_third_party.py`).*\n" % rel)
        return False
    data = open(path, "rb").read().decode("utf-8", "replace").replace("\r\n", "\n")
    digest = hashlib.sha256(data.encode("utf-8")).hexdigest()
    if digest in seen:
        out.append("`%s` is identical to `%s` (shown above)." % (rel, seen[digest]))
        out.append("")
        return True
    seen[digest] = rel
    out.append("`%s`" % rel)
    out.append("")
    out.append("~~~text")
    out.append(data.rstrip("\n"))
    out.append("~~~")
    out.append("")
    return True


def main():
    cfg = json.load(open(os.path.join(ROOT, "tools", "third_party.json"), encoding="utf-8"))
    out = ["# Third-party notices", "",
           "Generated by `tools/gen_notices.py` from `tools/third_party.json`; texts are verbatim copies of the files named.",
           "The credits tables (what each item is used for, where it lives, and whether it is modified) are in",
           "`README.md` and in chapter 14 of `Documentation/ironkernel64_spec.md`.", "",
           "Commodore 64 is a trademark of its owner. IronKernel 64 is an unaffiliated hobby project and contains no Commodore ROMs.", ""]
    ok = True
    for e in cfg["entries"]:
        n = e["name"]
        out += ["## %s" % n, "",
                "- Source: %s at commit `%s`" % (e["url"], e["commit"]),
                "- Licence: %s" % e["license"], ""]
        for f in LICENSE_FILES.get(n, []):
            ok &= text_block("third_party/%s/%s" % (n, f), out)
        if n == "open-roms":
            src = os.path.join(ROOT, "third_party", n, "pngprepare.c")
            if os.path.isfile(src):
                head = open(src, encoding="utf-8", errors="replace").read().split("*/")[0] + "*/"
                out += ["`third_party/open-roms/pngprepare.c` (header, X11 licence):", "", "~~~text", head, "~~~", ""]
    out += ["## Redip-SID gateware headers", "",
            "Every reDIP-SID `.sv` file carries the CERN-OHL-S v2 header naming Dag Lem; the licence text is under `redip-sid` above.", ""]
    for title, lic, rel in EXTRAS:
        out += ["## %s" % title, "", "- Licence: %s" % lic, ""]
        ok &= text_block(rel, out)
    out += ["## IronKernel 64 (this repository)", "", "- Licence: GPL-3.0-or-later (firmware, tools, scripts); GPL-3.0-or-later OR CERN-OHL-S-2.0 (gateware)", ""]
    ok &= text_block("LICENSE", out)
    out += ["## Items without a licence text here", "",
            "- AMD IP, BSP and tools (Vivado and Vitis 2026.1): AMD licence terms, not reproduced.",
            "- IronKernel network core netlist and library: closed; licence exception wording is the owner's decision (owner to confirm).",
            "- Mutopia Project edition of Bach's Two-Part Invention No. 13 (Allen Garvin after the Bach-Gesellschaft): Public Domain.",
            "- Colodore palette (Pepto), Bauer VIC-II article, siddump, SD2IEC, HVSC, PSID format: reference only, no text copied.", ""]
    dest = os.path.join(ROOT, "docs", "THIRD_PARTY_NOTICES.md")
    open(dest, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("wrote %s%s" % (dest, "" if ok else " (some files missing)"))
    return 0 if ok else 1


sys.exit(main())
