# File: redip_patch.py
# Role: builds third_party/redip-sid/ik64/ from the unmodified upstream reDIP-SID gateware
#   (third_party/redip-sid/gateware, https://github.com/daglem/reDIP-SID, CERN-OHL-S-2.0).
#   ik64/ holds the compiled set used by fpga/hdl/sid_player.sv: sid_pkg.sv sid_api.sv
#   sid_control.sv sid_waveform.sv sid_waveform_PST.svh sid_waveform__ST.svh sid_envelope.sv
#   sid_pot.sv sid_dac.sv sid_voice.sv sid_filter.sv and every *.hex table those files load.
#
# Deterministic edits (register: fpga/DEVIATIONS.md; D4 is the muladd.sv substitution, not made here):
#   D1  sid_api.sv: remove the `initial begin $dumpfile(...); $dumpvars; end` block.
#   D2  sid_filter.sv: `unique0 case` -> `case` (Active-HDL 11.1 parse error).
#   D3  every .sv/.svh: `default_nettype none -> `default_nettype wire (Vivado 2026.1 Synth 8-6735).
# Each edit must match its expected count exactly or the script fails. Every modified file gets a
# prepended comment naming the change, the date, the deviation IDs and the original file and commit
# (CERN-OHL-S-2.0 section 3.3); unmodified files (the .hex tables) are copied byte-exact.
#
# Usage (run by tools/setup_third_party.py as a post step of the "redip-sid" entry):
#   python -I tools/redip_patch.py <gateware dir> <output dir>
# Exit codes: 0 done, 1 an edit did not match its expected count or an input is missing, 2 usage.
#
# Revision:
#   11-09-2026  first version
#   11-09-2026  D3 count checked once (in edit())

import re
import sys
from pathlib import Path

UPSTREAM_COMMIT = "56608673b3a4e4f637afc026dca07ebdbf7d0769"
MODIFIED_ON = "2026-11-09"  # fixed string: date of the commit that added this manifest step
SV_FILES = ["sid_pkg.sv", "sid_api.sv", "sid_control.sv", "sid_waveform.sv",
            "sid_waveform_PST.svh", "sid_waveform__ST.svh", "sid_envelope.sv",
            "sid_pot.sv", "sid_dac.sv", "sid_voice.sv", "sid_filter.sv"]
HEX_RE = re.compile(rb'\$readmemh\(\s*"([^"]+)"')

# IK64_DEVIATION D1
D1_OLD = b'    initial begin\n        $dumpfile("sid_api.fst");\n        $dumpvars;\n    end\n\n'
# IK64_DEVIATION D2
D2_OLD, D2_NEW = b"unique0 case", b"case"
# IK64_DEVIATION D3
D3_OLD, D3_NEW = b"`default_nettype none", b"`default_nettype wire"

DESC = {
    "D1": "removed the $dumpfile/$dumpvars initial block",
    "D2": "unique0 case -> case",
    "D3": "`default_nettype none -> wire",
}


class PatchError(Exception):
    pass


def edit(name, data, old, new, count, dev):
    """edit -- replaces old by new and requires exactly count matches.

    Returns: the edited bytes.
    """
    got = data.count(old)
    if got != count:
        raise PatchError("%s %s: expected %d match(es), found %d" % (name, dev, count, got))
    return data.replace(old, new)


def header(name, devs):
    """header -- modification notice prepended to a changed file.

    Returns: bytes.
    """
    lines = ["// MODIFIED by IronKernel 64 on %s (CERN-OHL-S-2.0 section 3.3)." % MODIFIED_ON,
             "// Original: gateware/%s of reDIP-SID, commit %s," % (name, UPSTREAM_COMMIT),
             "// https://github.com/daglem/reDIP-SID. Generated by tools/redip_patch.py.",
             "// Deviations (fpga/DEVIATIONS.md): %s" % ", ".join(devs)]
    lines += ["//   %s: %s" % (d, DESC[d]) for d in devs]
    return ("\n".join(lines) + "\n").encode("ascii")


def patch(name, data):
    """patch -- applies D1..D3 to one source file.

    Returns: (new bytes, deviation id list).
    """
    devs = []
    if name == "sid_api.sv":
        data = edit(name, data, D1_OLD, b"", 1, "D1")
        devs.append("D1")
    if name == "sid_filter.sv":
        data = edit(name, data, D2_OLD, D2_NEW, 1, "D2")
        devs.append("D2")
    data = edit(name, data, D3_OLD, D3_NEW, 1, "D3")
    devs.append("D3")
    return header(name, devs) + data, devs


def main(argv):
    """main -- builds the ik64 directory.

    Returns: process exit code.
    """
    if len(argv) != 3:
        print("usage: redip_patch.py <gateware dir> <output dir>", file=sys.stderr)
        return 2
    src, dst = Path(argv[1]), Path(argv[2])
    try:
        dst.mkdir(parents=True, exist_ok=True)
        hexes = set()
        for name in SV_FILES:
            path = src / name
            if not path.is_file():
                raise PatchError("missing input %s" % path)
            raw = path.read_bytes()
            hexes.update(h.decode() for h in HEX_RE.findall(raw))
            out, devs = patch(name, raw)
            (dst / name).write_bytes(out)
            print("redip_patch: %-24s %s" % (name, ",".join(devs)))
        for name in sorted(hexes):
            path = src / name
            if not path.is_file():
                raise PatchError("missing table %s" % path)
            (dst / name).write_bytes(path.read_bytes())
            print("redip_patch: %-24s copied" % name)
        print("redip_patch: PASS (%d sources, %d tables)" % (len(SV_FILES), len(hexes)))
        return 0
    except PatchError as exc:
        print("redip_patch: FAIL: %s" % exc, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
