# check_credits.py -- fails when an item present in the repository or the image is missing from the credits.
#   1. every entry of tools/third_party.json must appear (by name or alias) in README.md, in the credits chapter
#      of Documentation/ironkernel64_spec.md and in docs/THIRD_PARTY_NOTICES.md, and its commit prefix in the spec;
#   2. every score bank/public/<tune>.txt: its title and file name must appear in the spec's public bank table and
#      its composer name in the spec;
#   3. every source file whose header says "Derived from", "Adapted from", "Copied from" or "Generated by
#      MenuBuilder" must have its repository path in the spec credits tables.
# Usage: python -I tools/check_credits.py            (from the repository root or anywhere)
# Exit 0 when complete, 1 when something is missing, 2 on a missing input file.
# Revision: 11-10-2026
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
ALIASES = {
    "libsmb2": ["libsmb2"],
    "open-roms": ["open roms", "open-roms"],
    "resid": ["resid"],
    "dormann": ["dormann"],
    "redip-sid": ["redip-sid"],
}
HEADER_RE = re.compile(r"(Derived from|Adapted from|Copied from|Generated by MenuBuilder|Base: RTLNet)")
SKIP_DIRS = {"third_party", "build", "node_modules", ".git", ".claude", "ironkernel", "diagrams", "Documentation", "docs"}
SKIP_FILES = {"check_credits.py", "gen_notices.py", "c64demo.md", "README.md"}
EXTS = {".c", ".h", ".sv", ".svh", ".tcl", ".py", ".ps1", ".xdc", ".f", ".asm", ".txt", ".def", ".sh"}


def read(rel):
    path = os.path.join(ROOT, rel)
    if not os.path.isfile(path):
        print("MISSING INPUT: %s" % rel)
        sys.exit(2)
    return open(path, encoding="utf-8", errors="replace").read()


def main():
    readme = read("README.md").lower()
    spec = read("Documentation/ironkernel64_spec.md")
    spec_l = spec.lower()
    notices = read("docs/THIRD_PARTY_NOTICES.md").lower()
    bad = []
    checked = 0

    cfg = json.loads(read("tools/third_party.json"))
    for e in cfg["entries"]:
        n = e["name"]
        names = ALIASES.get(n, [n.lower()])
        for label, text in (("README.md", readme), ("spec", spec_l), ("notices", notices)):
            checked += 1
            if not any(a in text for a in names):
                bad.append("third_party.json entry '%s' is not in the %s" % (n, label))
        checked += 1
        if e["commit"][:8] not in spec_l:
            bad.append("third_party.json entry '%s': commit %s is not in the spec" % (n, e["commit"][:8]))
        checked += 1
        if e["url"].replace("https://", "").replace(".git", "").lower() not in spec_l:
            bad.append("third_party.json entry '%s': URL %s is not in the spec" % (n, e["url"]))

    bank = os.path.join(ROOT, "bank", "public")
    for f in sorted(os.listdir(bank)):
        if not f.endswith(".txt"):
            continue
        text = open(os.path.join(bank, f), encoding="utf-8").read()
        title = re.search(r"(?m)^title:\s*(.+)$", text).group(1).strip()
        author = re.search(r"(?m)^author:\s*(.+?)(?:,\s*arr\..*)?$", text).group(1).strip()
        stem = f[:-4]
        checked += 3
        if "bank/public/%s" % f not in spec:
            bad.append("tune score bank/public/%s is not in the spec" % f)
        if title.lower() not in spec_l:
            bad.append("tune title '%s' (%s) is not in the spec" % (title, f))
        surname = author.split()[-1].lower()
        if surname not in spec_l:
            bad.append("composer '%s' of %s is not in the spec" % (author, f))

    for dirpath, dirs, files in os.walk(ROOT):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for fn in files:
            if fn in SKIP_FILES or os.path.splitext(fn)[1] not in EXTS:
                continue
            path = os.path.join(dirpath, fn)
            try:
                head = open(path, encoding="utf-8", errors="replace").read(4000)
            except OSError:
                continue
            if HEADER_RE.search(head):
                rel = os.path.relpath(path, ROOT).replace(os.sep, "/")
                checked += 1
                if rel.lower() not in spec_l:
                    bad.append("%s says '%s' but its path is not in the spec credits" % (rel, HEADER_RE.search(head).group(1)))

    for b in bad:
        print("CREDITS MISSING: " + b)
    print("check_credits: %d checks, %d missing" % (checked, len(bad)))
    return 1 if bad else 0


sys.exit(main())
