  if (ADDR_W != 29 || DATA_W != 128 || ID_W != 2) begin : g_bad_cfg
    $fatal(1, "ik64_axi_cdc: ADDR_W=%0d DATA_W=%0d ID_W=%0d, the clock converter IP is 29/128/2", ADDR_W, DATA_W, ID_W);
